        /* ====== GLISSER (swipe) sur tactile : lightbox et photos d'activite ====== */
        (function () {
            function swipe(el, fn) {
                let x0 = null;
                el.addEventListener('touchstart', e => { x0 = e.touches[0].clientX; }, { passive: true });
                el.addEventListener('touchend', e => {
                    if (x0 === null) return;
                    const dx = e.changedTouches[0].clientX - x0; x0 = null;
                    if (Math.abs(dx) > 50) fn(dx < 0 ? 1 : -1);
                }, { passive: true });
            }
            const lb = document.getElementById('lightbox-modal');
            const md = document.getElementById('modal-content');
            if (lb) swipe(lb, d => lightboxNav(d));
            if (md) swipe(md, d => { if (modalImgs.length > 1) modalNav(d); });
        })();
