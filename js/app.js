        const EMAIL_RE = /^[A-Za-z0-9._%+\-]+@ensh\.dz$/i;
        function validateEmailField() {
            const input = document.getElementById('c-email');
            const hint = document.getElementById('c-email-hint');
            if (!input) return true;
            const v = input.value.trim();
            const ok = EMAIL_RE.test(v);
            input.setCustomValidity(ok || !v ? '' : t('email_error'));
            const bad = !!v && !ok;
            input.classList.toggle('input-error', bad);
            if (hint) hint.classList.toggle('field-hint-error', bad);
            return ok;
        }

